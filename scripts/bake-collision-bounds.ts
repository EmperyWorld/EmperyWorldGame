import { readdir, writeFile } from 'node:fs/promises';
import sharp from 'sharp';
import { boundsFromImageData } from '../packages/shared/src/prop-silhouette-math.js';
const bounds:Record<string,ReturnType<typeof boundsFromImageData>>={};
for(const file of (await readdir('data/generated/assets')).filter(name=>name.startsWith('prop_')&&name.endsWith('.webp')).sort()) {
  const {data,info}=await sharp(`data/generated/assets/${file}`).resize(96,96,{fit:'fill'}).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  bounds[file.slice(0,-5)]=boundsFromImageData({width:info.width,height:info.height,data:new Uint8ClampedArray(data)});
}
await writeFile('packages/shared/src/prop-opaque-bounds.ts',`// Generated by pnpm bake:collision. Commit with changed prop assets.\nimport type { PropOpaqueNorm } from './prop-silhouette-math.js';\nexport const PROP_OPAQUE_BOUNDS: Record<string,PropOpaqueNorm|null> = ${JSON.stringify(bounds)};\n`);
console.log(`Baked ${Object.keys(bounds).length} prop collision bounds`);
