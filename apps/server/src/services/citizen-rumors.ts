/**
 * Night greeting for a district citizen, if the world clock is at rest hours.
 */
export function citizenNightGreeting(npcId: string, hour?: number): string | undefined {
  if (hour == null || !isNpcRestHour(hour)) return undefined;
  return DISTRICT_NIGHT_GREETINGS[npcId];
}

/**
 * Возвращает случайный слух для района.
 */
export function getCitizenRumors(npcId: string, hour?: number): string {
  const nightPool =
    hour != null && isNpcRestHour(hour) ? DISTRICT_NIGHT_RUMORS[npcId] : undefined;
  const pool =
    (nightPool && nightPool.length > 0 ? nightPool : DISTRICT_RUMORS[npcId]) ??
    DISTRICT_RUMORS.haven_citizen_plaza!;
  return pool[Math.floor(Math.random() * pool.length)]!;
}

/**
 * Возвращает практический совет для района.
 */
export function getCitizenAdvice(npcId: string, hour?: number): string {
  if (hour != null && isNpcRestHour(hour) && DISTRICT_NIGHT_ADVICE[npcId]) {
    return DISTRICT_NIGHT_ADVICE[npcId]!;
  }
  return DISTRICT_ADVICE[npcId] ?? DISTRICT_ADVICE.haven_citizen_plaza!;
}

/**
 * Формирует приветствие с учётом подвигов персонажа.
 */
export function formatCitizenGreeting(
  baseGreeting: string,
  save: PlayerSave,
): { text: string; mood: 'happy' | 'serious' | 'angry' | 'neutral' } {
  const recognition = getCitizenRecognition(save);
  if (recognition) {
    return {
      text: `«${recognition.text}»\n\n${baseGreeting}`,
      mood: recognition.mood,
    };
  }
  return {
    text: baseGreeting,
    mood: 'neutral',
  };
}
