import { isNpcRestHour, type PlayerSave } from '@empery/shared';

export interface CitizenRecognition {
  text: string;
  mood: 'happy' | 'serious' | 'angry' | 'neutral';
}

/**
 * Проверяет подвиги и репутацию игрока для контекстной реакции горожан.
 */
export function getCitizenRecognition(save: PlayerSave): CitizenRecognition | null {
  // 1. L2-style karma: positive values mark a chaotic/PK player.
  if ((save.karma ?? 0) > 0) {
    return {
      text: 'Эй... руки на виду держи! От тебя за версту разит кровью и раздором. В Гавани чтят закон — сходи к отцу Кассиану в Собор, пока стража не взялась за кандалы.',
      mood: 'angry',
    };
  }

  // 2. Спаситель лаборатории Штаб-квартиры EmperyWorld
  if (save.questFlags.quest_hq_lab_complete) {
    return {
      text: 'Ты ведь тот самый исследователь, что запустил биополе в лаборатории Штаба EmperyWorld? Об этом открытии говорит вся инженерная гильдия!',
      mood: 'happy',
    };
  }

  // 3. Выполненная городская охота с доски объявлений
  if (save.questFlags.quest_board_bounty_complete) {
    return {
      text: 'Стражники передают из уст в уста: опасный контракт с городской доски закрыт твоим клинком! В предместьях наконец-то можно вздохнуть спокойно.',
      mood: 'happy',
    };
  }

  // 4. Доставка рыбы от Ульфа в трактир
  if (save.questFlags.quest_fish_delivery_complete) {
    return {
      text: 'Слышал, благодаря твоей доставке в таверне Марты сегодня подают жареную форель с пряными травами. Отличная работа!',
      mood: 'happy',
    };
  }

  // 5. Победы в кости Гавани
  const diceWins = Number(save.questFlags.haven_dice_wins ?? 0);
  if (diceWins >= 2) {
    return {
      text: `Говорят, в трактире у Марты объявился мастер костей — уже ${diceWins} побед на игорном столе! Удача благоволит смелым.`,
      mood: 'happy',
    };
  }

  // 6. Активное благословение Собора
  if (Number(save.questFlags.buff_sup_cathedral_blessing_val ?? 0) > 0) {
    return {
      text: 'От тебя веет благодатью и священным покоем Собора. Отец Кассиан благословил твоё оружие на добрые дела!',
      mood: 'happy',
    };
  }

  // 7. Вдохновение барда Кая
  if (Number(save.questFlags.buff_sup_bard_inspiration_val ?? 0) > 0) {
    return {
      text: 'Какая стремительная поступь! Видать, бард Кай сыграл для тебя свою лучшую песнь под сводами амфитеатра.',
      mood: 'happy',
    };
  }

  // 8. Спасение Рощи Серебряного Леса
  if (save.questFlags.quest_grove_complete) {
    return {
      text: 'Вести из Серебряного Леса достигли Гавани: Роща спасена! Мы помним, кто сражался за неё против гоблинов.',
      mood: 'happy',
    };
  }

  // 9. Опытный ветеран (высокий уровень)
  if ((save.level ?? 1) >= 10) {
    return {
      text: `Взгляните, идёт закалённый воин ${save.level}-го ранга! Таким защитникам в Гавани всегда почёт и уважение.`,
      mood: 'happy',
    };
  }

  return null;
}

